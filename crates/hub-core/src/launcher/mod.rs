    // TC-LAUNCH-09: PATH lookup finds an executable file in any PATH entry
    // and rejects non-executable or missing files. Runs on every unix host
    // (macOS included) via a synthetic PATH; nothing is executed.
    #[cfg(unix)]
    #[test]
    fn tc_launch_09_find_executable_in_path() {
        use std::os::unix::fs::PermissionsExt;

        let empty_dir = tempfile::tempdir().unwrap();
        let tools_dir = tempfile::tempdir().unwrap();
        let executable = tools_dir.path().join("hub-fake-term");
        std::fs::write(&executable, b"#!/bin/sh\n").unwrap();
        std::fs::set_permissions(&executable, std::fs::Permissions::from_mode(0o755)).unwrap();
        let non_executable = tools_dir.path().join("hub-not-executable");
        std::fs::write(&non_executable, b"x").unwrap();

        let path = std::env::join_paths([empty_dir.path(), tools_dir.path()]).unwrap();
        let path = path.as_os_str();
        // Found in the second PATH entry, returned as the full candidate path
        assert_eq!(
            find_executable_in_path("hub-fake-term", Some(path)),
            Some(executable)
        );
        // Exists but not executable, or entirely missing: no hit
        assert_eq!(
            find_executable_in_path("hub-not-executable", Some(path)),
            None
        );
        assert_eq!(find_executable_in_path("hub-missing", Some(path)), None);
        // No PATH value at all: no hit
        assert_eq!(find_executable_in_path("hub-fake-term", None), None);
    }

    // TC-LAUNCH-10: Windows terminal quoting — the whole command becomes one
    // double-quoted argument; internal double quotes are escaped; single
