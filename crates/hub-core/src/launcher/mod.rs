    // TC-LAUNCH-11: Windows ZCode.exe probe locations — per-user install
    // first, then per-machine Program Files variants; no bases means no
    // candidates. Expected values are built with join() to stay
    // separator-agnostic across test hosts.
    #[test]
    fn tc_launch_11_windows_zcode_candidates() {
        use std::path::Path;

        let local = Path::new("C:/Users/x/AppData/Local");
        let program_files = Path::new("C:/Program Files");
        let program_files_x86 = Path::new("C:/Program Files (x86)");
        let candidates =
            zcode_windows_candidates(Some(local), Some(program_files), Some(program_files_x86));
        assert_eq!(
            candidates,
            vec![
                local.join("Programs").join("ZCode").join("ZCode.exe"),
                program_files.join("ZCode").join("ZCode.exe"),
                program_files_x86.join("ZCode").join("ZCode.exe"),
            ]
        );
        assert!(candidates.iter().all(|path| path
            .file_name()
            .and_then(|name| name.to_str())
            .is_some_and(|name| name.eq_ignore_ascii_case("zcode.exe"))));
        assert_eq!(
            zcode_windows_candidates(None, Some(program_files), None),
            vec![program_files.join("ZCode").join("ZCode.exe")]
        );
        assert!(zcode_windows_candidates(None, None, None).is_empty());
    }
